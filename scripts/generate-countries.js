// One-off generator for src/data/countries.ts — run manually with:
//   npm install --no-save i18n-iso-countries && node scripts/generate-countries.js
// Not part of the app bundle; i18n-iso-countries is only a dev-time input.
const fs = require('fs');
const path = require('path');
const { getCountries, getCountryCallingCode } = require('libphonenumber-js');
const isoCountries = require('i18n-iso-countries');
isoCountries.registerLocale(require('i18n-iso-countries/langs/en.json'));

const NAME_OVERRIDES = {
  AC: 'Ascension Island',
  TA: 'Tristan da Cunha',
  US: 'United States',
  BQ: 'Bonaire, Sint Eustatius and Saba',
  CD: 'DR Congo',
  CN: 'China',
  FK: 'Falkland Islands',
  FM: 'Micronesia',
  IO: 'British Indian Ocean Territory',
  LA: 'Laos',
  MF: 'Saint Martin',
  MK: 'North Macedonia',
  TZ: 'Tanzania',
  VA: 'Vatican City',
  KR: 'South Korea',
  KP: 'North Korea',
  RU: 'Russia',
  SY: 'Syria',
  TW: 'Taiwan',
  VN: 'Vietnam',
  MD: 'Moldova',
  BN: 'Brunei',
  IR: 'Iran',
  BO: 'Bolivia',
  VE: 'Venezuela',
};

function isoToFlagEmoji(iso2) {
  return iso2
    .toUpperCase()
    .replace(/./g, (char) => String.fromCodePoint(127397 + char.charCodeAt(0)));
}

const entries = getCountries()
  .map((iso2) => {
    const name = NAME_OVERRIDES[iso2] || isoCountries.getName(iso2, 'en');
    if (!name) return null;
    return {
      iso2,
      name,
      dialCode: getCountryCallingCode(iso2),
      flag: isoToFlagEmoji(iso2),
    };
  })
  .filter(Boolean)
  .sort((a, b) => a.name.localeCompare(b.name));

const header = `// Generated by scripts/generate-countries.js — do not edit by hand.
export interface Country {
  iso2: string;
  name: string;
  dialCode: string;
  flag: string;
}

export const countries: Country[] = `;

const body = JSON.stringify(entries, null, 2) + ';\n';

fs.writeFileSync(path.join(__dirname, '../src/data/countries.ts'), header + body);
console.log(`Wrote ${entries.length} countries to src/data/countries.ts`);
